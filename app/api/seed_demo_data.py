async def clean_test_data(session) -> None:
    """Keep baseline employees 1-3 and remove generated test data."""
    baseline = list((await session.execute(
        select(Employee).where(Employee.employee_code.in_(["EMP001", "EMP-HR-001", "EMP-DM-001"]))
    )).scalars())
    baseline_employee_ids = {employee.id for employee in baseline}
    baseline_user_ids = {employee.user_id for employee in baseline if employee.user_id}
    baseline_user_ids.add(1)  # technical super-admin
    baseline_unit_ids = {employee.unit_id for employee in baseline if employee.unit_id}
    baseline_department_ids = {employee.department_id for employee in baseline if employee.department_id}
    baseline_designation_ids = {employee.designation_id for employee in baseline if employee.designation_id}

    # Operational rows contain actor foreign keys, so clear them before users.
    for model in (
        AttendanceCorrectionRequest, AttendanceDiscrepancy, AttendancePunch,
        OvertimeApproval, OvertimeRecord, AttendanceRecord, AuditLog, LeaveLedgerEntry,
        LeaveApplication, LeaveBalance, LeaveAllocation, WorkArrangementRequest,
        EmployeeWorkHistory, DepartmentApprover, ShiftAssignment, Notification,
        AuthSession,
    ):
        await session.execute(delete(model))

    await session.execute(delete(Employee).where(Employee.id.not_in(baseline_employee_ids)))
    await session.execute(delete(User).where(User.id.not_in(baseline_user_ids)))
    await session.execute(update(Employee).values(shift_id=None))
    await session.execute(delete(Holiday))
    await session.execute(delete(HolidayList))
    await session.execute(delete(LeavePeriod))
    await session.execute(delete(LeaveType).where(LeaveType.id != 1))
    await session.execute(delete(Shift))
    await session.execute(delete(Department).where(Department.id.not_in(baseline_department_ids)))
    await session.execute(delete(Unit).where(Unit.id.not_in(baseline_unit_ids)))
    await session.execute(delete(Designation).where(Designation.id.not_in(baseline_designation_ids)))
    await session.commit()


async def get_or_create(session, model, lookup: dict, values: dict):
    item = await session.scalar(select(model).filter_by(**lookup))
    if item is None:
        item = model(**lookup, **values)
        session.add(item)
        await session.flush()
    return item


